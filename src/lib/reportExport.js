// Activity report downloads. Built in the browser from the rows the person is allowed to see; PDF and Excel libraries load only when needed.
import { downloadCsv, toCsv } from './csv'
import { fmtDateTimeTz, fmtDateTz, fmtTimeTz } from './tz'
import { actionLabel } from '../services/audit'

const place = (r) => [r.city, r.region, r.country].filter(Boolean).join(', ')
const json = (v) => (v ? JSON.stringify(v) : '')
export const safeFile = (s) => String(s || 'report').replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '').toLowerCase().slice(0, 60) || 'report'

export const CSV_COLUMNS = ['Timestamp (UTC)', 'Local date', 'Local time', 'Employee', 'User ID', 'Action', 'Module', 'Record ID', 'Description', 'Status', 'IP address', 'IP source',
  'Country', 'State/Region', 'City', 'ISP', 'Browser', 'Device', 'OS', 'Previous data', 'Updated data', 'Metadata']
export const csvRow = (r, tz) => ({
  'Timestamp (UTC)': new Date(r.created_at).toISOString(), 'Local date': fmtDateTz(r.created_at, tz), 'Local time': fmtTimeTz(r.created_at, tz), Employee: r.username, 'User ID': r.user_id || '',
  Action: actionLabel(r.action), Module: r.module, 'Record ID': r.record_id || '', Description: r.description, Status: r.status, 'IP address': r.ip_address || '',
  'IP source': r.metadata?.ip_source || '', Country: r.country || '', 'State/Region': r.region || '', City: r.city || '', ISP: r.isp || '', Browser: r.browser || '', Device: r.device || '', OS: r.os || '',
  'Previous data': json(r.previous_data), 'Updated data': json(r.updated_data), Metadata: json(r.metadata),
})

export function exportCsv(rows, tz, name) { downloadCsv(`${name}.csv`, toCsv(CSV_COLUMNS, rows.map((r) => csvRow(r, tz)))) }

const kpis = (s) => [
  ['Total activities', s.total], ['Successful', s.success], ['Failed', s.failed], ['Failed login attempts', s.failed_logins],
  ['Records created', s.created], ['Records updated', s.updated], ['Records deleted', s.deleted], ['Emails sent', s.emails_sent], ['WhatsApp messages sent', s.whatsapp_sent],
  ['Unique IP addresses', s.unique_ips], ['Approximate locations', (s.locations || []).filter((l) => l.location).length],
]
const NOTE = 'Locations are approximate and based on IP addresses. VPNs, proxies, mobile networks and shared connections can make them inaccurate. They are not GPS positions.'

export async function exportXlsx(rows, summary, meta, name) {
  const { default: ExcelJS } = await import('exceljs')
  const wb = new ExcelJS.Workbook(); wb.creator = meta.generatedBy; wb.created = new Date()
  const head = { font: { bold: true, color: { argb: 'FFFFFFFF' } }, fill: { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF4B4BC4' } } }

  const sm = wb.addWorksheet('Summary', { views: [{ showGridLines: false }] })
  sm.columns = [{ width: 34 }, { width: 46 }]
  sm.addRow([meta.title]).font = { bold: true, size: 16 }
  sm.addRow([])
  ;[['Employee', meta.employee], ['Employee ID', meta.employeeId], ['Reporting period', meta.period], ['Time zone', meta.tz], ['Generated', fmtDateTimeTz(new Date().toISOString(), meta.tz)], ['Generated by', meta.generatedBy]]
    .forEach(([k, v]) => { const r = sm.addRow([k, v]); r.getCell(1).font = { bold: true } })
  sm.addRow([])
  sm.addRow(['Metric', 'Value']).eachCell((c) => Object.assign(c, head))
  kpis(summary).forEach(([k, v]) => sm.addRow([k, v ?? 0]))
  sm.addRow(['First recorded activity', fmtDateTimeTz(summary.first_at, meta.tz)]); sm.addRow(['Last recorded activity', fmtDateTimeTz(summary.last_at, meta.tz)])
  sm.addRow([]); sm.addRow(['Activity by module', 'Count']).eachCell((c) => Object.assign(c, head)); (summary.by_module || []).forEach((m) => sm.addRow([m.module, m.count]))
  sm.addRow([]); sm.addRow(['Approximate locations', 'Count']).eachCell((c) => Object.assign(c, head)); (summary.locations || []).forEach((l) => sm.addRow([l.location || 'Not available', l.count]))
  sm.addRow([]); sm.addRow(['Activity by day', 'Count']).eachCell((c) => Object.assign(c, head)); (summary.by_day || []).forEach((d) => sm.addRow([d.day, d.count]))
  sm.addRow([]); const note = sm.addRow([NOTE]); sm.mergeCells(`A${note.number}:B${note.number}`); note.alignment = { wrapText: true, vertical: 'top' }; note.height = 48

  const ws = wb.addWorksheet('Activities', { views: [{ state: 'frozen', ySplit: 1 }] })
  const cols = [['Timestamp (UTC)', 22], ['Local time', 22], ['Employee', 20], ['User ID', 38], ['Action', 18], ['Module', 14], ['Record ID', 38], ['Description', 60], ['Status', 10], ['IP address', 16], ['IP source', 16],
    ['Country', 14], ['State/Region', 16], ['City', 16], ['ISP', 22], ['Browser', 12], ['Device', 10], ['OS', 10], ['Previous data', 40], ['Updated data', 40]]
  ws.columns = cols.map(([header, width]) => ({ header, width }))
  ws.getRow(1).eachCell((c) => Object.assign(c, head))
  rows.forEach((r) => ws.addRow([new Date(r.created_at), fmtDateTimeTz(r.created_at, meta.tz), r.username, r.user_id || '', actionLabel(r.action), r.module, r.record_id || '', r.description, r.status, r.ip_address || '',
    r.metadata?.ip_source || '', r.country || '', r.region || '', r.city || '', r.isp || '', r.browser || '', r.device || '', r.os || '', json(r.previous_data), json(r.updated_data)]))
  ws.getColumn(1).numFmt = 'yyyy-mm-dd hh:mm:ss'
  ws.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: cols.length } }
  const buf = await wb.xlsx.writeBuffer()
  const url = URL.createObjectURL(new Blob([buf], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' }))
  const a = Object.assign(document.createElement('a'), { href: url, download: `${name}.xlsx` }); document.body.appendChild(a); a.click(); a.remove(); setTimeout(() => URL.revokeObjectURL(url), 1000)
}

function bars(doc, x, y, w, h, data, color = [75, 75, 196]) {
  const max = Math.max(1, ...data.map((d) => d.value)); const bw = w / Math.max(1, data.length)
  doc.setDrawColor(200); doc.line(x, y + h, x + w, y + h)
  data.forEach((d, i) => {
    const bh = (d.value / max) * (h - 8); doc.setFillColor(...color); if (bh > 0) doc.rect(x + i * bw + bw * 0.15, y + h - bh, bw * 0.7, bh, 'F')
    doc.setFontSize(6); doc.setTextColor(90); doc.text(String(d.label), x + i * bw + bw / 2, y + h + 7, { align: 'center' })
    if (d.value) { doc.setTextColor(40); doc.text(String(d.value), x + i * bw + bw / 2, y + h - bh - 2, { align: 'center' }) }
  })
}

export async function exportPdf(rows, summary, meta, name, { maxRows = 3000 } = {}) {
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([import('jspdf'), import('jspdf-autotable')])
  const doc = new jsPDF({ orientation: 'landscape', unit: 'pt', format: 'a4' }); const W = doc.internal.pageSize.getWidth(); const M = 36
  doc.setFont('helvetica', 'bold'); doc.setFontSize(18); doc.setTextColor(20, 22, 31); doc.text(meta.title, M, 48)
  doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(90)
  doc.text(`Employee: ${meta.employee}    ID: ${meta.employeeId}`, M, 66)
  doc.text(`Period: ${meta.period}    Time zone: ${meta.tz}`, M, 79)
  doc.text(`Generated ${fmtDateTimeTz(new Date().toISOString(), meta.tz)} by ${meta.generatedBy}`, M, 92)

  const k = kpis(summary); const half = Math.ceil(k.length / 2)
  autoTable(doc, { startY: 108, head: [['Summary', '', '', '']], body: Array.from({ length: half }, (_, i) => [k[i][0], String(k[i][1] ?? 0), k[i + half]?.[0] || '', k[i + half] ? String(k[i + half][1] ?? 0) : '']),
    theme: 'grid', styles: { fontSize: 8.5, cellPadding: 4 }, headStyles: { fillColor: [75, 75, 196] }, columnStyles: { 1: { halign: 'right', cellWidth: 70 }, 3: { halign: 'right', cellWidth: 70 } }, margin: { left: M, right: M } })
  let y = doc.lastAutoTable.finalY + 8
  doc.setFontSize(8.5); doc.setTextColor(60)
  doc.text(`First activity: ${fmtDateTimeTz(summary.first_at, meta.tz)}    Last activity: ${fmtDateTimeTz(summary.last_at, meta.tz)}`, M, y + 8); y += 22

  const days = (summary.by_day || []).slice(-31).map((d) => ({ label: d.day.slice(5), value: d.count }))
  const mods = (summary.by_module || []).slice(0, 10).map((m) => ({ label: m.module.slice(0, 9), value: m.count }))
  if (y > 380) { doc.addPage(); y = M }
  doc.setFont('helvetica', 'bold'); doc.setFontSize(10); doc.setTextColor(20); doc.text('Daily activity', M, y); doc.text('Activity by module', W / 2 + 10, y)
  doc.setFont('helvetica', 'normal')
  if (days.length) bars(doc, M, y + 14, W / 2 - M - 20, 90, days); if (mods.length) bars(doc, W / 2 + 10, y + 14, W / 2 - M - 10, 90, mods, [16, 185, 129]); y += 135

  const locs = (summary.locations || []).slice(0, 8).map((l) => [l.location || 'Not available', String(l.count)])
  if (locs.length) { autoTable(doc, { startY: y, head: [['Approximate location (from IP address)', 'Activities']], body: locs, theme: 'striped', styles: { fontSize: 8.5 }, headStyles: { fillColor: [75, 75, 196] }, columnStyles: { 1: { halign: 'right', cellWidth: 70 } }, margin: { left: M, right: M } }); y = doc.lastAutoTable.finalY + 6 }
  doc.setFontSize(7.5); doc.setTextColor(120); doc.text(doc.splitTextToSize(NOTE, W - 2 * M), M, y + 8)

  doc.addPage()
  const shown = rows.slice(0, maxRows)
  autoTable(doc, {
    startY: M, head: [['Time', 'Employee', 'Activity', 'Module', 'IP address', 'Location', 'Device / browser', 'Status']],
    body: shown.map((r) => [fmtDateTimeTz(r.created_at, meta.tz), r.username, r.description || actionLabel(r.action), r.module, r.ip_address || '—', place(r) || 'Not available', [r.device, r.browser].filter(Boolean).join(' / ') || '—', r.status]),
    styles: { fontSize: 7, cellPadding: 3, overflow: 'linebreak' }, headStyles: { fillColor: [75, 75, 196] }, margin: { left: M, right: M, top: M, bottom: M },
    columnStyles: { 0: { cellWidth: 92 }, 1: { cellWidth: 70 }, 2: { cellWidth: 200 }, 3: { cellWidth: 55 }, 4: { cellWidth: 70 }, 6: { cellWidth: 90 }, 7: { cellWidth: 45 } },
    didParseCell: (d) => { if (d.section === 'body' && d.column.index === 7 && d.cell.raw === 'failed') d.cell.styles.textColor = [200, 40, 40] },
  })
  if (rows.length > shown.length) { doc.setFontSize(8); doc.setTextColor(120); doc.text(`Showing the first ${shown.length} of ${rows.length} activities. Download the Excel or CSV report for the complete list.`, M, doc.lastAutoTable.finalY + 14) }
  const pages = doc.getNumberOfPages()
  for (let i = 1; i <= pages; i++) { doc.setPage(i); doc.setFontSize(7.5); doc.setTextColor(140); doc.text(`${meta.title} · ${meta.employee} · Page ${i} of ${pages}`, W / 2, doc.internal.pageSize.getHeight() - 16, { align: 'center' }) }
  doc.save(`${name}.pdf`)
}
